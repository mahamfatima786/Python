# Arithemtic Operator
x = 5
y = 10
print(x+y) # This operator add the value of variables.
print(x-y) # This operator sub the value of variables.
print(x*y) # This operator multi the value of variables.
print(x/y) # This operator divide the value of variables.
print(x%y) # This operator show the remainder of the value of variables after division.
print(x**y) # This operator make the second variable(y) power of first variable (x).

# Comparision Operator
x = 5
y = 10
print(x==y) # This operator equal the value of variables.
print(x>=y)
print(x<=y)
print(x!=y)

# Logical Operator
x = 5
y = 10
print(x>y and x<y)
print(x>y or x<y)
print(not(x<y))

