# Common String Methods:)
str = "Quantessa"
print(str.upper()) # Converts all characters to uppercase.
print(str.lower()) # Converts all characters to lowercase.
print(str.title()) # Capitalizes the first letter of each word.
print(str.find("t")) # Returns index of first occurrence.
print(str.replace("e", "w")) # Replaces all occurrences.
print(str.count("n")) # Counts occurrences 
print(str.endswith("a"))  # Checks if string ends with given substring.

